def apply(mutant: Mutant, original: str) -> str:
    return original.replace(mutant.find, mutant.replace)


def run_mutant(mutant: Mutant, log_dir: Path | None) -> str:
    target = REPO / mutant.path
    original = target.read_text()
    found = original.count(mutant.find)
    if found != mutant.count:
        return f"ERROR: {mutant.name}: patch anchors {found}, want {mutant.count}"
    try:
        target.write_text(apply(mutant, original))
        run = subprocess.run(
            ["go", "test", *PACKAGES, "-run", mutant.run, "-count=1"],
            cwd=REPO,
            capture_output=True,
            text=True,
            timeout=300,
        )
    finally:
        target.write_text(original)
    output = (run.stdout + run.stderr).strip()
    if os.environ.get("AX_MUTANT_VERBOSE") == "1":
        print(f"--- raw: {mutant.name}: exit {run.returncode} ---", flush=True)
        print(output, flush=True)
        print(f"--- end raw: {mutant.name} ---", flush=True)
    if log_dir is not None:
        (log_dir / f"{mutant.name}.log").write_text(
            f"exit: {run.returncode}\nrun: go test {' '.join(PACKAGES)} -run {mutant.run} -count=1\n\n{output}\n"
        )
    if 'build failed' in output or '\n# ' in output or output.startswith('# '):
        return f"ERROR: {mutant.name}: build broke under the patch"
    if run.returncode == 0:
        verdict = "SURVIVED"
    elif '--- FAIL' in output or 'FAIL:' in output:
        verdict = "KILLED"
    else:
        return f"ERROR: {mutant.name}: exit {run.returncode} with no kill line"
    mark = "ok" if verdict == mutant.expect else "MISMATCH"
    return f"{mark}: {mutant.name}: {verdict} (want {mutant.expect}) :: {mutant.note} [exit {run.returncode}]"


def main(argv: list[str]) -> int:
    log_dir: Path | None = None
    names = list(argv)
    selected_slice: tuple[int, int] | None = None
    if "--log-dir" in names:
        idx = names.index("--log-dir")
        if idx + 1 >= len(names):
            print("--log-dir needs a directory")
            return 2
        log_dir = Path(names[idx + 1])
        log_dir.mkdir(parents=True, exist_ok=True)
        del names[idx : idx + 2]
    if "--slice" in names:
        idx = names.index("--slice")
        if idx + 1 >= len(names):
            print("--slice needs START:END")
            return 2
        if idx != 0 or len(names) != 2:
            print("--slice cannot be combined with mutant names")
            return 2
        try:
            start, end = (int(value) for value in names[idx + 1].split(":"))
        except (ValueError, TypeError):
            print("--slice needs integer START:END")
            return 2
        if start < 0 or end <= start or end > len(MUTANTS):
            print(f"--slice bounds must satisfy 0 <= START < END <= {len(MUTANTS)}")
            return 2
        selected_slice = (start, end)
        del names[idx : idx + 2]
    selected = (
        MUTANTS[selected_slice[0] : selected_slice[1]]
        if selected_slice is not None
        else [m for m in MUTANTS if not names or m.name in names]
    )
    if names and len(selected) != len(names):
        unknown = sorted(set(names) - {m.name for m in selected})
        print(f"unknown mutants: {', '.join(unknown)}")
        return 2
    failures = 0
    for mutant in selected:
        try:
            line = run_mutant(mutant, log_dir)
        except subprocess.TimeoutExpired:
            line = f"ERROR: {mutant.name}: killer timed out"
        print(line, flush=True)
        if not line.startswith("ok:"):
            failures += 1
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
