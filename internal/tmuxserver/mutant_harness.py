def custody_permission_mask_mutants() -> list[Mutant]:
    """Drop each member of the owner-only permission mask at each gate."""
    rows: list[Mutant] = []
    scopes = (
        (
            "socket",
            f"{PACKAGE}/bind.go",
            "\treturn permissions&0o077 == 0 && permissions&0o600 == 0o600 &&\n"
            "\t\tmode&(os.ModeSetuid|os.ModeSetgid|os.ModeSticky) == 0\n",
            "socket_leaf",
        ),
        (
            "root",
            f"{PACKAGE}/bind.go",
            "\treturn permissions&0o077 == 0 && permissions&0o700 == 0o700 &&\n"
            "\t\tmode&(os.ModeSetuid|os.ModeSetgid|os.ModeSticky) == 0\n",
            "root",
        ),
        (
            "runtime-dir",
            f"{PACKAGE}/runtime_unix.go",
            "\treturn permissions&0o077 == 0 && permissions&0o700 == 0o700 &&\n"
            "\t\tmode&(os.ModeSetuid|os.ModeSetgid|os.ModeSticky) == 0\n",
            "runtime_tmux_dir",
        ),
    )
    bits = (
        ("group-read", "0o040", "group_read"),
        ("group-write", "0o020", "group_write"),
        ("group-execute", "0o010", "group_execute"),
        ("other-read", "0o004", "other_read"),
        ("other-write", "0o002", "other_write"),
        ("other-execute", "0o001", "other_execute"),
    )
    for scope, path, find, component in scopes:
        def add(name: str, narrowed: str, note: str) -> None:
            rows.append(
                Mutant(
                    name=f"N-{scope}-mask-{name}",
                    path=path,
                    find=find,
                    replace=find.replace("permissions&0o077", narrowed, 1),
                    count=1,
                    run="TestCustodyModeOracleAtProductionEntries",
                    expect="KILLED",
                    note=note,
                )
            )

        add("drop-group-triplet", "permissions&0o007", f"Ignores the group triplet at {component}; the isolated exhaustive oracle runs through Probe, Spawn and Execute.")
        add("drop-other-triplet", "permissions&0o070", f"Ignores the other triplet at {component}; the isolated exhaustive oracle runs through Probe, Spawn and Execute.")
        for label, bit, test_name in bits:
            add(
                f"drop-{label}",
                f"permissions&(0o077 &^ {bit})",
                f"Ignores only outside-owner bit {bit} at {component}; the isolated exhaustive oracle runs through Probe, Spawn and Execute.",
            )

    ancestor_find = "\tif perm&0o022 == 0 {\n"
    for label, replacement, test_name in (
        ("group-write", "\tif perm&0o002 == 0 {\n", "group_write"),
        ("other-write", "\tif perm&0o020 == 0 {\n", "other_write"),
    ):
        rows.append(
            Mutant(
                name=f"N-ancestor-mask-drop-{label}",
                path=f"{PACKAGE}/bind.go",
                find=ancestor_find,
                replace=replacement,
                count=1,
                run="TestCustodyModeOracleAtProductionEntries",
                expect="KILLED",
                note=f"Drops only the {label} term from the ancestor write mask. The isolated exhaustive oracle drives all modes through Probe, Spawn and Execute.",
            )
        )
    return rows


