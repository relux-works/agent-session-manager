#!/usr/bin/env python3
"""Narrowing-mutant harness for internal/tmuxserver.

Every gate ships a narrowing mutant: the gate stays present and is
weakened to admit exactly one member of the class it must reject, and
the named killer tests must fail. A delete-only mutant proves only that
the gate exists and is not accepted as evidence; the six D- rows are
explicitly supplementary and not counted as any gate's narrowing: three
additive plants (D-background-fallback,
D-background-fallback-foreground, D-restore-replay-rotation), two
positive-path wiring checks (D-lifecycle-restore-authkind,
D-lifecycle-terminate-authkind), and one shadowed narrowing
(D-attach-entry-deadline-shadowed, which survives by reroute to the
wait bound), each labeled as such in its note.

Each row runs M (mutate production files in place), R (run the scoped Go
killers through the production entries), V (verdict from the Go exit code
plus a FAIL kill-line: KILLED iff R fails with a test failure line,
SURVIVED iff R passes, ERROR for anything else -- unapplied patches,
build breaks, timeouts). M failures and R infrastructure errors are
ERROR, never kills or survivals. Files are restored from backups after
every row, pass or fail.

Row C-control is the harmless control: a comment-only edit that must
SURVIVE, proving the harness observes test outcomes instead of
hard-coding kills.

Usage:
  PYTHONDONTWRITEBYTECODE=1 python3 internal/tmuxserver/mutant_harness.py
  PYTHONDONTWRITEBYTECODE=1 python3 internal/tmuxserver/mutant_harness.py N-mode-create
  PYTHONDONTWRITEBYTECODE=1 python3 internal/tmuxserver/mutant_harness.py --slice 0:50 --log-dir .temp/mutants/group-01
  PYTHONDONTWRITEBYTECODE=1 python3 internal/tmuxserver/mutant_harness.py --log-dir .temp/TASK-ID/mutant-logs
  AX_MUTANT_VERBOSE=1 PYTHONDONTWRITEBYTECODE=1 python3 internal/tmuxserver/mutant_harness.py N-mode-create
"""

